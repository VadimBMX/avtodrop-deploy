// Spinning wheels in the drag race (owner 27.10: «шоб крутились колеса, або просто ілюзію»).
// Over each wheel of the car photo sits a disc showing the same photo, turned by a Web Animation whose playbackRate
// follows the car's speed on the strip — so painted cars (only the body is repainted, the wheels stay as photographed)
// and season liveries (the CSS filter is copied) spin too. The photos are slightly perspective, so a wheel is an
// ellipse: the disc turns in the wheel's own plane and is mapped onto that ellipse (.ww-e: rotate(tilt) scaleY(b/a)),
// with the photo inside un-mapped first (.ww-p: the inverse) — at rest it is pixel for pixel the photo, and while it
// turns the rim stays on its ellipse. Above a few turns a second the turn rate is capped (a faster turn would strobe on
// a 60 Hz screen) and trailing copies + a soft rim haze stand in for motion blur. Wheels whose rim could not be fitted
// cleanly (owner 28.10: «криво крутяться») are blur-only: the photo stays, a streak turns over it.
// Wheel data: race-wheels-data.js, generated by tools/race_wheels.py from the photos (it also scores every disc).
// Nothing here touches the race maths: it only reads the metres app.js already draws.
import { MODELS } from './shared.js';
import { WW_DATA } from './race-wheels-data.js';

export const WW_CAP = 2.4; // max shown turns per second (5-spoke rim: 17°/frame at 60 Hz, still reads as forward)
const PXM = 9; // screen px per metre of track (DR_PXM in app.js)

// Wheel data for a race model: its own photo's, else the photo a season livery borrows (MODELS[id].img).
// → { w, h, wheels: [{ cx, cy, a, b, t, spin }] } (photo px, t = tilt in degrees) or null.
export function wheelData(id, data = WW_DATA) {
  for (const k of [id, MODELS[id]?.img]) {
    const x = k && data[k];
    if (x) return { w: x[0], h: x[1], wheels: x[2].map(([cx, cy, a, b, t, spin]) => ({ cx, cy, a, b, t, spin: !!spin })) };
  }
  return null;
}

// One wheel in % of the photo box. The frame (.ww-e) is the square of side 2a around the centre; `ell` maps it onto
// the wheel's ellipse. The photo layer (.ww-p, in % of the frame) lines the photo up with the one underneath and
// `inv` (about the wheel centre, `origin`) undoes `ell`, so frame ∘ photo = identity at rest.
export function wheelBox(w, h, { cx, cy, a, b, t }) {
  return {
    left: ((cx - a) / w) * 100, top: ((cy - a) / h) * 100, size: ((2 * a) / w) * 100,
    ell: `rotate(${t}deg) scaleY(${(b / a).toFixed(5)})`,
    pw: (w / (2 * a)) * 100, pl: (-(cx - a) / (2 * a)) * 100, pt: (-(cy - a) / (2 * a)) * 100,
    origin: `${((cx / w) * 100).toFixed(4)}% ${((cy / h) * 100).toFixed(4)}%`,
    inv: `scaleY(${(a / b).toFixed(5)}) rotate(${-t}deg)`,
  };
}

// Shown turns per second for a car at v m/s with a wheel of rPx screen px: true rolling, capped; the blur level 0–3.
export function spinOf(v, rPx) {
  const real = v > 0.05 && rPx > 0 ? (v * PXM) / (2 * Math.PI * rPx) : 0;
  return { rate: Math.min(real, WW_CAP), lvl: real <= 0 ? 0 : real < WW_CAP * 0.9 ? 1 : real < WW_CAP * 2.2 ? 2 : 3 };
}

const f = (n) => n.toFixed(4);
const KEYS = [{ transform: 'rotate(0deg)' }, { transform: 'rotate(360deg)' }];

function wheelHtml(d, q) {
  const b = wheelBox(d.w, d.h, q);
  const photo = `<i class="ww-p" style="width:${f(b.pw)}%;left:${f(b.pl)}%;top:${f(b.pt)}%;aspect-ratio:${d.w} / ${d.h};transform-origin:${b.origin};transform:${b.inv}"></i>`;
  const inner = q.spin ? `${photo}<i class="ww-k k1">${photo}</i><i class="ww-k k2">${photo}</i>` : '<i class="ww-z"></i>';
  return `<i class="ww-e${q.spin ? '' : ' blur'}" style="left:${f(b.left)}%;top:${f(b.top)}%;width:${f(b.size)}%;transform:${b.ell}"><i class="ww-s">${inner}</i><b class="ww-g"></b></i>`;
}

// The race scene's wheels: mount(E) after the scene is (re)built, tick(myM, rvM) every frame with the drawn metres.
export function raceWheels(R, { reduced = false } = {}) {
  const cars = { me: { model: R.car.model }, rv: { model: R.rival.model } };
  if (reduced || typeof Element === 'undefined' || !Element.prototype.animate) return { mount() {}, tick() {} };
  let last = 0;
  function build(who, bod) {
    const c = cars[who];
    bod.querySelector(':scope > .ww')?.remove();
    c.wheels = [];
    c.lvl = -1;
    c.m = null;
    const img = bod.querySelector('img');
    const d = img && wheelData(c.model);
    if (!d) return;
    const src = img.currentSrc || img.getAttribute('src');
    if (!src) return;
    const el = document.createElement('div');
    el.className = 'ww';
    el.style.aspectRatio = `${d.w} / ${d.h}`;
    if (img.style.filter) el.style.filter = img.style.filter;
    el.innerHTML = d.wheels.map((q) => wheelHtml(d, q)).join('');
    // The photo URL goes in through CSSOM (a painted car's src can be a long blob/data URL; quotes stay safe).
    const url = `url("${src.replace(/"/g, '%22')}")`;
    el.querySelectorAll('.ww-p').forEach((p) => (p.style.backgroundImage = url));
    bod.appendChild(el);
    c.el = el;
    c.W = bod.offsetWidth; // fixed in CSS (146 / 112 px): read once here, never in the frame loop
    c.wheels = [...el.querySelectorAll('.ww-s')].map((s, i) => ({ a: s.animate(KEYS, { duration: 1000, iterations: Infinity }), rate: 0,
      rel: Math.sqrt(d.wheels[i].a * d.wheels[i].b) / d.w, rear: i === 0 && d.wheels.length > 1 }));
    c.wheels.forEach((w) => (w.a.playbackRate = 0));
    // A photo that changed size since the wheel data was taken: no discs rather than discs in the wrong place.
    const check = () => img.naturalWidth && Math.abs(img.naturalWidth / img.naturalHeight - d.w / d.h) > 0.02 && (el.remove(), (c.wheels = []));
    img.complete ? check() : img.addEventListener('load', check, { once: true });
  }
  return {
    mount(E) {
      build('me', E.meB);
      build('rv', E.rvB);
    },
    tick(myM, rvM) {
      const now = performance.now(), dt = last ? Math.min(0.1, (now - last) / 1000) : 0;
      last = now;
      for (const [who, m] of [['me', myM], ['rv', rvM]]) {
        const c = cars[who];
        if (!c.wheels?.length) continue;
        if (c.m == null) (c.m = m, c.v = 0);
        if (dt > 0) {
          const v = Math.max(0, (m - c.m) / dt);
          c.v += (v - c.v) * Math.min(1, dt * 12);
          if (m === c.m && v === 0) c.v *= 0.8; // stopped (start line, or a frame without movement)
        }
        c.m = m;
        if (c.v > 0.05 && c.go == null) c.go = now;
        let lvl = 0;
        for (const w of c.wheels) {
          const s = spinOf(c.v < 0.05 ? 0 : c.v, w.rel * c.W);
          // Launch: the rear wheel spins up first (the burnout smoke is already there).
          const rate = w.rear && c.go != null && now - c.go < 450 ? Math.max(s.rate, WW_CAP) : s.rate;
          lvl = Math.max(lvl, s.lvl);
          if (rate === 0 ? w.rate !== 0 : Math.abs(rate - w.rate) > 0.06 * Math.max(rate, w.rate)) {
            w.rate = rate;
            if (w.a.updatePlaybackRate) w.a.updatePlaybackRate(rate);
            else w.a.playbackRate = rate;
          }
        }
        if (lvl !== c.lvl) (c.lvl = lvl, c.el.dataset.s = String(lvl));
      }
    },
  };
}
