// Writes public/car-photos.js: the ids of every photo in public/cars. A car from NEW_RAW (public/shared.js) is in the
// game only when its id is listed there. `npm run cars` writes the same file itself; run this one
// (npm run car-photos) after copying a ready photo straight into public/cars or after deleting one.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'public', 'cars');

export function photoIds(dir = DIR) {
  if (!fs.existsSync(dir)) return [];
  const ids = fs.readdirSync(dir).map((f) => /^([a-z0-9-]+)\.(webp|png|jpe?g)$/i.exec(f)?.[1]).filter(Boolean);
  return [...new Set(ids)].sort();
}

export function photosModule(ids) {
  return '// Generated by `npm run cars` / `npm run car-photos` from the files in public/cars — do not edit by hand.\n'
    + '// A car from NEW_RAW in shared.js is in the game only when its id is here.\n'
    + 'export const CAR_PHOTOS = [\n' + ids.map((id) => `  '${id}',\n`).join('') + '];\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ids = photoIds();
  fs.writeFileSync(path.join(ROOT, 'public', 'car-photos.js'), photosModule(ids));
  const { PENDING_MODELS } = await import('../public/shared.js');
  const waiting = Object.values(PENDING_MODELS);
  console.log(`public/car-photos.js: ${ids.length} photos. ${waiting.length ? `Waiting for a photo (${waiting.length}): ${waiting.map((m) => m.id).join(', ')}` : 'Every car has a photo.'}`);
}
